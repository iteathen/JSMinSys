// Build-time specialization: retain the ordering authority, exclude the move
// already searched in the cheap tier before any score calculation.
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
const input=new URL('../addons/connect4-live-line-order.mjs',import.meta.url),
  output=new URL('../addons/connect4-staged-live-line-order.mjs',import.meta.url),
  authority=readFileSync(input,'utf8').replaceAll('\r\n','\n');
function extract(name){
  const start=authority.indexOf('export function '+name+'('),open=authority.indexOf('){',start)+1;
  assert.ok(start>=0&&open>start);let end=open+1,depth=1;
  for(;depth;end++){assert.ok(end<authority.length);if(authority[end]==='{')depth++;if(authority[end]==='}')depth--;}
  return authority.slice(start,end);
}
let text=`// GENERATED by tools/build-connect4-staged-live-order.mjs.
import {prepareConnect4LiveLineOrder32} from './connect4-live-line-order.mjs';

// COLD: reuse geometry, storage and update kernels; select the remainder order.
export function prepareConnect4StagedLiveLineOrder32(g,centerOrder,moves){
  const o=prepareConnect4LiveLineOrder32(g,centerOrder,moves);
  o.order=o.shift<0?orderConnect4StagedLiveLineGeneral32:orderConnect4StagedLiveLinePacked32;
  return o;
}

// First tier touches only support and prepared center order, never live scores.
export function beginConnect4StagedLiveLineOrder32(o,words,src,row){
  const columns=o.g.columns,rows=o.g.rows,center=o.centerOrder,ordered=o.ordered;
  for(let i=0;i<columns;i+=1){
    const c=center[i];
    if(words[src+c]<rows){ordered[row]=c;return 1;}
  }
  return 0;
}
`;
for(const suffix of ['Packed32','General32']){
  let s=extract('orderConnect4LiveLine'+suffix);
  s=s.replace('orderConnect4LiveLine'+suffix,'orderConnect4StagedLiveLine'+suffix)
    .replace('liveOffset,row){','liveOffset,row,excludedColumn){');
  const old='const c=centerOrder[i],h=words[src+c];if(h>=rows)continue;';
  assert.equal(s.split(old).length,2);
  s=s.replace(old,'const c=centerOrder[i];if(c===excludedColumn)continue;\n    const h=words[src+c];if(h>=rows)continue;');
  text+='\n'+s+'\n';
}
if(process.argv.includes('--check'))assert.equal(readFileSync(output,'utf8').replaceAll('\r\n','\n'),text);
else writeFileSync(output,text);
