// COLD: specialize only closure application and cold three-word/span choice.
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
function closeBrace(s,open){let end=open+1,depth=1;for(;depth;end++){assert.ok(end<s.length);if(s[end]==='{')depth++;if(s[end]==='}')depth--;}return end;}
function extract(s,name){const start=s.indexOf('function '+name+'('),open=s.indexOf('){',start)+1;assert.ok(start>=0&&open>start);return s.slice(start,closeBrace(s,open));}
for(const dense of [false,true]){
 const kind=dense?'Dense':'Prepared',authority=readFileSync(new URL('../addons/rba-connect4-coordinate-support-'+(dense?'dense':'prepared')+'.mjs',import.meta.url),'utf8').replaceAll('\r\n','\n');
 let text="// GENERATED by tools/build-rba-support-closure-kernels.mjs; complete closure plan required.\n"+
  "import {loadSupportClosureBasis32,applySupportClosureSpan32} from './rba-connect4-support-basis-plan.mjs';\n";
 for(const nonWinning of [false,true])for(const three of [false,true]){
  const name='connect4RbaSupport'+kind+'Cofactor'+(nonWinning?'NonWinning':'')+'KnownHeight';
  let s=extract(authority,name);
  function once(a,b){assert.equal(s.split(a).length,2,a);s=s.replace(a,b);}
  once('loadSupportBasis32(g,target,dst,childBasis,ci,seen)','loadSupportClosureBasis32(g,target,dst,childBasis,ci,seen,removed,childIndex)');
  once('  for(let j=0;j<cn;j+=1)childIndex[childBasis[ci+j]]=j;','');
  once('offsets=profile.supersetWordOffsets,words=profile.supersetWords,masks=profile.supersetMasks;',
   'closures=g.supportBasisPlans.closures,closureBase=removed[0]*g.maxBasis*g.coordWords;');
  const start=s.indexOf('    if(write0)target[p0Target+targetWord]|=targetMask;'),loop=s.indexOf('    for(let at=',start),open=s.indexOf('{',loop),end=closeBrace(s,open);
  assert.ok(start>0&&loop>start&&open>loop);
  s=s.slice(0,start)+'    '+(three?'applySupportClosure3x32':'applySupportClosureSpan32')+'(closures,closureBase+lo*g.coordWords,g.coordWords,target,p0Target,p1Target,write0,write1);'+s.slice(end);
  if(three){
   // Cold three-word selection already supplies the exact family. Absorption
   // and expansion share six local outputs, never intermediate child memory.
   const clear='for(let w=0;w<2*g.coordWords;w+=1)target[dst+g.p0Offset+w]=0;';
   once('  '+clear+'\n','');
   if(!nonWinning)once('const value=player?1:3;target[dst+g.metaOffset]',
    'const value=player?1:3;'+clear+'target[dst+g.metaOffset]');
   once('if(rank+1===g.cellCount){target[dst+g.metaOffset]',
    'if(rank+1===g.cellCount){'+clear+'target[dst+g.metaOffset]');
   once('  const activeWords=(n+31)>>>5;',
    '  let out00=0,out01=0,out02=0,out10=0,out11=0,out12=0;\n  const activeWords=(n+31)>>>5;');
   once('write0=write0&&!(target[p0Target+targetWord]&targetMask);',
    'write0=write0&&!((targetWord===0?out00:targetWord===1?out01:out02)&targetMask);');
   once('write1=write1&&!(target[p1Target+targetWord]&targetMask);',
    'write1=write1&&!((targetWord===0?out10:targetWord===1?out11:out12)&targetMask);');
   once('    applySupportClosure3x32(closures,closureBase+lo*g.coordWords,g.coordWords,target,p0Target,p1Target,write0,write1);',
    '    const at=closureBase+lo*g.coordWords,a=closures[at],b=closures[at+1],c=closures[at+2];\n'+
    '    if(write0){out00|=a;out01|=b;out02|=c;}\n'+
    '    if(write1){out10|=a;out11|=b;out12|=c;}');
   once('  return 0;\n}',
    '  target[p0Target]=out00;target[p0Target+1]=out01;target[p0Target+2]=out02;\n'+
    '  target[p1Target]=out10;target[p1Target+1]=out11;target[p1Target+2]=out12;\n  return 0;\n}');
  }
  text+='export '+s.replace(name,'connect4RbaClosure'+kind+(three?'3':'Span')+'Cofactor'+(nonWinning?'NonWinning':'')+'KnownHeight')+'\n';
 }
 const output=new URL('../addons/rba-connect4-coordinate-closure-'+(dense?'dense':'prepared')+'.mjs',import.meta.url);
 if(process.argv.includes('--check'))assert.equal(readFileSync(output,'utf8').replaceAll('\r\n','\n'),text);
 else writeFileSync(output,text);
}
