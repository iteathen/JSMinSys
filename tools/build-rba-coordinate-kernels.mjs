// COLD build tool. Canonical coordinate semantics own both prepared kernels.
// Dimensions remain initialization data; no board-size constants are embedded.
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
const root=new URL('../',import.meta.url);
const authority=readFileSync(new URL('addons/rba-connect4-coordinate.mjs',root),'utf8').replaceAll('\r\n','\n');
function once(s,a,b){assert.equal(s.split(a).length,2,a);return s.replace(a,b);}
function extract(name){
  const start=authority.indexOf('function '+name+'('),open=authority.indexOf('){',start)+1;
  assert.ok(start>=0&&open>start);let end=open+1,depth=1;
  for(;depth;end++){assert.ok(end<authority.length);if(authority[end]==='{')depth++;if(authority[end]==='}')depth--;}
  return authority.slice(start,end);
}
for(const dense of [false,true]){
  let s="import {emitSortedSetBits32} from '../src/basis32.mjs';\nexport {connect4RbaCanonicalize} from './rba-connect4-coordinate.mjs';\n"+
    extract('connect4RbaCofactorBasis')+'\nexport '+extract('connect4RbaCofactorKnownHeight')+'\n';
  s=s.replaceAll('removed=null,childIndex=null,seenOffset=0','removed,childIndex').replaceAll('removed=null,seenOffset=0','removed');
  s=s.replaceAll('removed,seenOffset','removed').replaceAll('seenOffset+','');
  s=once(s,'if(removed)removed[i]=id;','removed[i]=id;');
  s=once(s,'return seenOffset\n    ?emitSortedSetBitsAt32(seen,seenOffset,g.shapeWordCount,out,outOffset)\n    :emitSortedSetBits32(seen,g.shapeWordCount,out,outOffset);','return emitSortedSetBits32(seen,g.shapeWordCount,out,outOffset);');
  s=once(s,'if(childIndex)for(let j=0;j<cn;j+=1)','for(let j=0;j<cn;j+=1)');
  s=once(s,'const remove=removed?0:profile.prepareRemove(g,cell),','const');
  s=once(s,'raw=removed?removed[i]:profile.removePrepared(g,id,remove)','raw=removed[i]');
  s=once(s,'    if(childIndex)lo=childIndex[image];\n    else{\n      lo=0;let hi=cn;\n      while(lo<hi){const mid=(lo+hi)>>>1;if(childBasis[ci+mid]<image)lo=mid+1;else hi=mid;}\n    }','    lo=childIndex[image];');
  s=once(s,'        if(childIndex)j=childIndex[id];\n        else{\n          j=0;let hi=cn;\n          while(j<hi){const mid=(j+hi)>>>1;if(childBasis[ci+mid]<id)j=mid+1;else hi=mid;}\n        }','        j=childIndex[id];');
  if(dense){
    s=once(s,'const remove=profile.prepareRemove(g,cell);','const remove=cell*g.shapeCount,removeByCell=g.removeByCell;');
    s=once(s,'const id=profile.removePrepared(g,parent[parentOffset+i],remove);','const id=removeByCell[remove+parent[parentOffset+i]];');
  }
  if(dense)s+="export {connect4RbaPreparedCanonicalize} from './rba-connect4-coordinate-prepared.mjs';\n";
  else{
    s="import {publishSpan32} from '../src/widekey32.mjs';\n"+s;
    let canonical=extract('compareReflectedSupport')+'\nexport '+extract('connect4RbaCanonicalize')+'\n';
    canonical=canonical.replace(',selectedSet=null,selectedSetOffset=0','');
    canonical=once(canonical,'  if(selectedSet)publishSpan32(selectedSet,selectedSetOffset,scratch.seen,0,g.shapeWordCount);\n','');
    s+=canonical.replaceAll('compareReflectedSupport','comparePreparedReflectedSupport').replaceAll('connect4RbaCanonicalize','connect4RbaPreparedCanonicalize');
  }
  const kind=dense?'Dense':'Prepared';
  s=s.replaceAll('connect4RbaCofactorBasis','connect4Rba'+kind+'CofactorBasis').replaceAll('connect4RbaCofactorKnownHeight','connect4Rba'+kind+'CofactorKnownHeight');
  const text='// GENERATED by tools/build-rba-coordinate-kernels.mjs. Do not edit.\n'+
    '// Prepared-only contract: removed/inverse scratch required; seen offset zero.\n'+
    (dense?'// Dense kernel requires a non-null geometry removal table, selected cold.\n':'')+s;
  const path=new URL('addons/rba-connect4-coordinate-'+(dense?'dense':'prepared')+'.mjs',root);
  if(process.argv.includes('--check'))assert.equal(readFileSync(path,'utf8').replaceAll('\r\n','\n'),text);
  else writeFileSync(path,text);
}
