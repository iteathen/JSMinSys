// Build-time specialization only. No source rewriting, eval or generation in
// application initialization/search. Ordinary solver remains algorithm authority.
import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';

const baselinePath='addons/rba-connect4-alphabeta.mjs';
const original=readFileSync(baselinePath,'utf8').replaceAll('\r\n','\n');
const sha=createHash('sha256').update(original).digest('hex');
let source=original;
const start=source.indexOf('function searchCpcOnly('),end=source.indexOf('export function solveConnect4RbaAlphaBeta(');
assert.ok(start>0&&end>start);
let hot=source.slice(start,end);
// Complete normal returns before leaving each evaluated node. Propagating a
// cancellation is inserted afterward and must not poll or finalize ancestors.
hot=hot.replace(/return ([^;\n]+);/g,'return completeBehaviorNode32(state, $1);');
assert.equal((hot.match(/      continue;/g)||[]).length,1);
hot=hot.replace('      continue;','      if (completeBehaviorNode32(state, 0) === 3) return 3;\n      continue;');
hot=hot.replace(/value=-search(?:CpcOnly)?\([\s\S]*?;/g,'$&\n        if (value === -3) return 3;');
// Terminal cofactors are completed child nodes, even though baseline nodes
// counts only nonterminal recursive/transit visits.
hot=hot.replaceAll('if(term)value=absToRelative(term,mover);',
  'if(term){value=absToRelative(term,mover);if(completeBehaviorNode32(state,value)===3)return 3;}');
hot=hot.replace('      if(term){\n        const value=',
  '      if(term){\n        if(completeBehaviorNode32(state,0)===3)return 3;\n        const value=');
source=source.slice(0,start)+hot+source.slice(end);

source=source.replace('  cpcProjectedAdvisory=false,','  cpcProjectedAdvisory=false,\n  behavior,');
source=source.replace('  return {g,profile,mode,','  return prepareSearchBehavior32({g,profile,mode,');
source=source.replace('    cofactors:0};','    cofactors:0},behavior);');

const rootAt=source.indexOf('export function solveConnect4RbaAlphaBeta(');
let root=source.slice(rootAt);
const cancelled="return {status:'CANCELLED',value:null,relative:null,move:-1,metrics:metrics(state)};";
root=root.replace(/value=-search(?:CpcOnly)?\([\s\S]*?;/g,`$&\n          if(value===-3){${cancelled}}`);
// Braces are needed around the baseline one-line else calls before injecting.
root=root.replace(/}else (value=-search\([^;]+;\n\s*if\(value===-3\)\{[^\n]+\})/g,'}else {$1}');
root=root.replace(/}else (value=-search\([^;]+;\n\s*if\(value===-3\)\{[^\n]+\})/g,'}else {$1}');
root=root.replaceAll('if(term)value=absToRelative(term,mover);',
 `if(term){value=absToRelative(term,mover);if(completeBehaviorNode32(state,value)===3){${cancelled}}}`);
root=root.replace('  if(terminal)return {value:terminal,relative:absToRelative(terminal,mover),move:-1,metrics:metrics(state)};',
 `  if(terminal){if(completeBehaviorNode32(state,0)===3){${cancelled}}return {status:'EXACT',value:terminal,relative:absToRelative(terminal,mover),move:-1,metrics:metrics(state)};}`);
root=root.replace('  return {value:relativeToAbs(relative,mover),relative,move:bestMove,metrics:metrics(state)};',
 `  if(completeBehaviorNode32(state,relative)===3){${cancelled}}\n  return {status:'EXACT',value:relativeToAbs(relative,mover),relative,move:bestMove,metrics:metrics(state)};`);
source=source.slice(0,rootAt)+root;

// Separate module-local identities and ledger names; no second manual algorithm.
const names=[...original.matchAll(/(?:export )?function (\w+)\(/g)].map(m=>m[1]);
for(const name of names)source=source.replace(new RegExp('\\b'+name+'(?=\\s*\\()','g'),name+'Behavior');
source=source.replaceAll('RBA_AB_CPC_ONLY','RBA_AB_CPC_ONLY_BEHAVIOR').replaceAll('RBA_AB_CPC_FOUR_FRONT','RBA_AB_CPC_FOUR_FRONT_BEHAVIOR');
source=`// GENERATED by tools/build-behavior-search.mjs; do not edit manually.\n// Baseline SHA256: ${sha}\n// Same algorithm; optional per-node controls and explicit cancellation only.\nimport {prepareSearchBehavior32,completeBehaviorNode32} from './worker-behavior-search.mjs';\n`+source;
const path='addons/rba-connect4-alphabeta-behavior.mjs';
if(process.argv.includes('--check'))assert.equal(readFileSync(path,'utf8').replaceAll('\r\n','\n'),source,'generated behavior search is stale');
else writeFileSync(path,source);

const workerOriginal=readFileSync('addons/rba-connect4-lazy-smp-worker.mjs','utf8').replaceAll('\r\n','\n');
let workerSource=workerOriginal.replace("'./rba-connect4-alphabeta.mjs'","'./rba-connect4-alphabeta-behavior.mjs'")
  .replaceAll('prepareConnect4RbaAlphaBeta','prepareConnect4RbaAlphaBetaBehavior')
  .replaceAll('solveConnect4RbaAlphaBeta','solveConnect4RbaAlphaBetaBehavior')
  .replaceAll('RBA_AB_CPC_ONLY','RBA_AB_CPC_ONLY_BEHAVIOR')
  .replace('    geometry:workerData.geometry,',
    '    geometry:workerData.geometry,\n    behavior:new BehaviorWorker(index,new Uint32Array(workerData.behaviorMemory.buffer),index,workerData.behaviorMemory),');
workerSource=workerSource.replace('Atomics.store(resultWords,resultBase,result.value);',`if(result.status==='CANCELLED'){
  // Cold completion only. Retire this worker, not the remaining searches.
  Atomics.store(resultWords,resultBase+3,-1);
  let allStopped=1;
  for(let i=0;i<workerData.workerCount;i+=1)
    if(Atomics.load(resultWords,i*RESULT_STRIDE+3)!==-1){allStopped=0;break;}
  if(allStopped){
    Atomics.compareExchange(control,2,0,103);
    Atomics.store(control,0,1);
    Atomics.add(control,CONTROL_WAKE,1);Atomics.notify(control,CONTROL_WAKE);
  }
  // A retired thread stays parked until host closure or another exact result.
  // No behavior-flag acknowledgments and no node-loop waits are introduced.
  while(!Atomics.load(control,0)&&!Atomics.load(control,CONTROL_DONE)){
    const observed=Atomics.load(control,CONTROL_WAKE);
    if(!Atomics.load(control,0)&&!Atomics.load(control,CONTROL_DONE))
      Atomics.wait(control,CONTROL_WAKE,observed);
  }
}else{
Atomics.store(resultWords,resultBase,result.value);`);
workerSource=`// GENERATED by tools/build-behavior-search.mjs; do not edit manually.\nimport {BehaviorWorker} from './worker-behavior.mjs';\n`+workerSource+'}\n';
const workerPath='addons/rba-connect4-lazy-smp-worker-behavior.mjs';
if(process.argv.includes('--check'))assert.equal(readFileSync(workerPath,'utf8').replaceAll('\r\n','\n'),workerSource,'generated behavior worker is stale');
else writeFileSync(workerPath,workerSource);
