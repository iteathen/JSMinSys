// COLD generator. The existing coordinate authority owns all terminal,
// projection, owner-survival and upward-closure semantics.
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
function extract(name,s){
 const start=s.indexOf('function '+name+'('),open=s.indexOf('){',start)+1;
 assert.ok(start>=0&&open>start);let end=open+1,depth=1;
 for(;depth;end++){assert.ok(end<s.length);if(s[end]==='{')depth++;if(s[end]==='}')depth--;}
 return s.slice(start,end);
}
for(const dense of [false,true]){
 const kind=dense?'Dense':'Prepared',input='rba-connect4-coordinate-'+(dense?'dense':'prepared')+'.mjs',
  authority=readFileSync(new URL('../addons/'+input,import.meta.url),'utf8').replaceAll('\r\n','\n');
 let text="// GENERATED by tools/build-rba-support-plan-kernels.mjs; complete cold support plan required.\n"+
  "import {loadSupportBasis32} from './rba-connect4-support-basis-plan.mjs';\n";
 for(const nonWinning of [false,true]){
  const name='connect4Rba'+kind+'Cofactor'+(nonWinning?'NonWinning':'')+'KnownHeight';
  let s=extract(name,authority);
  const old='const cn=connect4Rba'+kind+'CofactorBasis(g,profile,basis,bi,n,cell,childBasis,ci,seen,removed);sizes[sizeIndex]=cn;';
  assert.equal(s.split(old).length,2);
  s=s.replace(old,'const cn=loadSupportBasis32(g,target,dst,childBasis,ci,seen);sizes[sizeIndex]=cn;');
  assert.equal(s.split('raw=removed[i]').length,2);
  if(dense){
   s=s.replace('const\n    p0Source','const remove=cell*g.shapeCount,removal=g.removeByCell,\n    p0Source');
   s=s.replace('raw=removed[i]','raw=removal[remove+id]');
  }else{
   s=s.replace('const\n    p0Source','const remove=profile.prepareRemove(g,cell),\n    p0Source');
   s=s.replace('raw=removed[i]','raw=profile.removePrepared(g,id,remove)');
  }
  text+='export '+s.replace(name,'connect4RbaSupport'+kind+'Cofactor'+(nonWinning?'NonWinning':'')+'KnownHeight')+'\n';
 }
 const output=new URL('../addons/rba-connect4-coordinate-support-'+(dense?'dense':'prepared')+'.mjs',import.meta.url);
 if(process.argv.includes('--check'))assert.equal(readFileSync(output,'utf8').replaceAll('\r\n','\n'),text);
 else writeFileSync(output,text);
}
