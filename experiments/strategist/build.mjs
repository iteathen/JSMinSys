import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const base=readFileSync(new URL('../../addons/rba-connect4-alphabeta-behavior.mjs',import.meta.url),'utf8').replaceAll('\r\n','\n');
let source=base.replaceAll("from './","from '../../addons/").replaceAll("from '../src/","from '../../src/");
source=source.replace("from '../../addons/worker-behavior-search.mjs'","from './controls.mjs'");
source=`// EXPERIMENT GENERATED by experiments/strategist/build.mjs; never edit manually.\n// Input SHA256 ${createHash('sha256').update(base).digest('hex')}\n`+source;
const path=new URL('./search.generated.mjs',import.meta.url);
if(process.argv.includes('--check'))assert.equal(readFileSync(path,'utf8').replaceAll('\r\n','\n'),source);
else writeFileSync(path,source);
