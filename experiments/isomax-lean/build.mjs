function endBlock(s,open){let depth=1,i=open+1;for(;depth&&i<s.length;i++){if(s[i]==='{')depth++;if(s[i]==='}')depth--;}assert.equal(depth,0);return i;}
function functionText(s,name){
  const start=s.indexOf('function '+name+'(');assert.ok(start>=0,name);
  const open=s.indexOf('){',start)+1;assert.ok(open>start,name);
  return s.slice(start,endBlock(s,open));
}
// Applied only to pinned, balanced source blocks; --check detects source drift.
function fixedIf(s,condition,take){
  const needle='if('+condition+')';
  while(s.includes(needle)){
    const start=s.indexOf(needle),open=s.indexOf('{',start),end=endBlock(s,open);
    assert.match(s.slice(start+needle.length,open),/^\s*$/);
    let tail=end,other='';
    if(s.slice(end).match(/^\s*else\s*\{/)){
      const next=s.indexOf('{',end);tail=endBlock(s,next);other=s.slice(next+1,tail-1);
    }else if(s.slice(end).match(/^\s*else if/)){
      let next=end;
      do{const brace=s.indexOf('{',next);tail=endBlock(s,brace);
        if(s.slice(next,brace).match(/^\s*else\s*$/))other=s.slice(brace+1,tail-1);
        next=tail;
      }while(s.slice(tail).match(/^\s*else/));
      assert.ok(take||other,'generic specialization requires final else');
    }
    s=s.slice(0,start)+(take?s.slice(open+1,end-1):other)+s.slice(tail);
  }
  return s;
}
