import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
const [dir,arm]=process.argv.slice(2),load=p=>import(pathToFileURL(dir+'/'+p).href);
const {prepareConnect4RbaGeometry}=await load('addons/rba-connect4-geometry.mjs');
const {connect4RbaFromMoves}=await load('addons/rba-connect4-ingress.mjs');
const {prepareConnect4CpcScratch,evaluateConnect4CpcNonterminal32,CPC_EXACT,CPC_NONE,CPC_BOUND}=await load('addons/cpc-connect4.mjs');
const g=prepareConnect4RbaGeometry({columns:4,rows:4});
const q=connect4RbaFromMoves([0,1,0,0],{geometry:g,canonical:false});
const s=prepareConnect4CpcScratch(g,{frontierResponse:false});
q.words.fill(0,g.p0Offset,g.p0Offset+2*g.coordWords);
const result=evaluateConnect4CpcNonterminal32(g,q.words,0,q.basis,0,q.basis.length,s);
const exhaustion=arm==='A'||arm==='C';
assert.equal(result,exhaustion?CPC_EXACT:CPC_NONE,'residual exhaustion treatment');
assert.deepEqual([...s.interval],exhaustion?[2,2]:[1,3]);
const source=readFileSync(dir+'/addons/cpc-connect4.mjs','utf8');
const body=source.slice(source.indexOf('export function evaluateConnect4CpcNonterminal32'));
assert.equal(body.includes('const noWin=scratch.frontierResponse'),arm==='A'||arm==='B','response treatment');
console.log(JSON.stringify({arm,exhaustion:!!exhaustion,response:arm==='A'||arm==='B',passed:true}));
